# PlatformIO pre-build script (#620): writes src/wifi_secrets.h (gitignored) from an ini file with [wifi] ssid and
# password, at $DECK_PANEL_WIFI_INI or ~/.config/deckbridge/panel-wifi.ini. Without the file (CI), both are empty and
# the panel shows "Wi-Fi isn't set". The values never go into build flags or logs: this prints only "set" or "none".
# A stopgap until phone setup (#622): the password ends up in the firmware image, readable by anyone with the panel.
# configparser strips spaces around a value and keeps quotes: write `password = abc`, not "abc". From phrasedeck's.
import configparser
import os

Import("env")  # noqa: F821 (PlatformIO's SCons global)

path = os.environ.get("DECK_PANEL_WIFI_INI", os.path.expanduser("~/.config/deckbridge/panel-wifi.ini"))
ssid = password = ""
if os.path.exists(path):
    ini = configparser.ConfigParser(interpolation=None)
    ini.read(path)
    ssid = ini.get("wifi", "ssid", fallback="")
    password = ini.get("wifi", "password", fallback="")


def c_string(s):
    # Printable ASCII as is, " and \ escaped, anything else as UTF-8 octal escapes.
    return '"' + "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else
                         ("\\" + c if c in '"\\' else "".join("\\%03o" % b for b in c.encode()))
                         for c in s) + '"'


header = os.path.join(env.subst("$PROJECT_SRC_DIR"), "wifi_secrets.h")  # noqa: F821
text = ("// Generated by wifi_secrets.py from %s. Not in git.\n#pragma once\n"
        "#define DECK_PANEL_WIFI_SSID %s\n#define DECK_PANEL_WIFI_PASSWORD %s\n") % (
    os.path.basename(path), c_string(ssid), c_string(password))
# Rewritten only when changed, so a build with the same credentials doesn't recompile wifi_link.cpp.
if not os.path.exists(header) or open(header).read() != text:
    if os.path.exists(header):
        os.remove(header)
    # Created 0600 from the start: never readable by others, even for a moment.
    with os.fdopen(os.open(header, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as f:
        f.write(text)
print("wifi_secrets: %s" % ("set" if ssid else "none; the panel will say Wi-Fi isn't set"))
